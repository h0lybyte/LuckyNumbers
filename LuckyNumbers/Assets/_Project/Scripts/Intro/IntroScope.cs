using LuckyNumbers.Generated;
using LuckyNumbers.Model;
using VContainer;
using VContainer.Unity;

namespace LuckyNumbers.Intro
{
    /// <summary>Intro scene scope; parent is RootLifetimeScope. Plays in the player's generated universe.</summary>
    public sealed class IntroScope : LifetimeScope
    {
        protected override void Configure(IContainerBuilder builder)
        {
            builder.RegisterInstance(GameContent.Intro.Backdrop); // same system as the title, shown instantly
            builder.RegisterLuckyNumbersSpace();                  // generated by Roslyn
            builder.RegisterLuckyNumbersIntro();                  // generated by Roslyn
            builder.RegisterComponentInHierarchy<LuckyNumbers.Title.DiceView>(); // the title's dice, reused
            builder.RegisterComponentInHierarchy<LuckyNumbers.Core.ShipView>();  // the museum freighter
        }
    }
}
