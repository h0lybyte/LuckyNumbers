using LuckyNumbers.Generated;
using LuckyNumbers.Model;
using VContainer;
using VContainer.Unity;

namespace LuckyNumbers.Title
{
    /// <summary>Title scene scope; parent is RootLifetimeScope (set by the scene builder).</summary>
    public sealed class TitleScope : LifetimeScope
    {
        protected override void Configure(IContainerBuilder builder)
        {
            builder.RegisterInstance(GameContent.Title.Backdrop); // universe shown behind the title
            builder.RegisterLuckyNumbersSpace();                  // generated by Roslyn
            builder.RegisterLuckyNumbersTitle();                  // generated by Roslyn
            builder.RegisterComponentInHierarchy<LuckyNumbers.Core.ShipView>();   // your fighter, in the hangar
            builder.RegisterComponentInHierarchy<TitleMusic>();                   // menu, creation and hangar music
        }
    }
}
