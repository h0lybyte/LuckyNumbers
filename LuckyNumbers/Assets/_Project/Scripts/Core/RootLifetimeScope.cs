using LuckyNumbers.Generated;
using LuckyNumbers.Model;
using MessagePipe;
using VContainer;
using VContainer.Unity;

namespace LuckyNumbers.Core
{
    /// <summary>
    /// App-wide scope, lives across scenes. Registers MessagePipe, every generated (ln.event) broker
    /// and (ln.state) singleton, and the Core presenters (scene flow, input). Scene scopes are its children.
    /// </summary>
    public sealed class RootLifetimeScope : LifetimeScope
    {
        static RootLifetimeScope _instance;

        protected override void Awake()
        {
            // Every scene carries one (so any scene runs on its own in the editor); the first one wins, so
            // brokers, buffered events (the lucky number) and (ln.state) singletons survive scene loads.
            if (_instance != null && _instance != this)
            {
                DestroyImmediate(gameObject);
                return;
            }
            _instance = this;
            DontDestroyOnLoad(gameObject);
            base.Awake();
        }

        protected override void Configure(IContainerBuilder builder)
        {
            var options = builder.RegisterMessagePipe();
            builder.RegisterBuildCallback(c => GlobalMessagePipe.SetProvider(c.AsServiceProvider()));
            builder.RegisterModelEvents(options); // generated by ln.py gen
            builder.RegisterModelState();         // generated by ln.py gen
            builder.RegisterLuckyNumbersCore();   // generated by Roslyn from [Presenter]/[View]
            // Scoped: the root and each scene scope get their own AssetScope, released with that scope.
            builder.Register<AssetScope>(Lifetime.Scoped);
            builder.Register<WeaponRack>(Lifetime.Scoped);   // per scene too: weapon copies from Prefabs/Weapons
            builder.Register<ShipYard>(Lifetime.Scoped);     // ship hulls from Prefabs/Ships
            builder.Register<SceneCurtain>(Lifetime.Scoped); // when the scene may fade in
        }
    }
}
