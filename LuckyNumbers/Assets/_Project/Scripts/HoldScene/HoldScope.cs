using LuckyNumbers.Generated;
using LuckyNumbers.Model;
using LuckyNumbers.Planet;
using VContainer;
using VContainer.Unity;

namespace LuckyNumbers.HoldScene
{
    /// <summary>
    /// Hold scene scope; parent is RootLifetimeScope. First-person control borrowed from the Planet scene (its walk
    /// settings, no crash tremor), the crash site's overlay UI (fade, hint), the hold's config and its meshes.
    /// </summary>
    public sealed class HoldScope : LifetimeScope
    {
        protected override void Configure(IContainerBuilder builder)
        {
            builder.RegisterInstance(GameContent.Hold);
            builder.RegisterEntryPoint<HoldPresenter>().AsSelf();   // HoldClimbPresenter teleports through it
            var walk = GameContent.Planet.Clone();
            walk.CrashTremorDegrees = 0f;
            builder.RegisterInstance(walk);
            builder.RegisterEntryPoint<FirstPersonPresenter>().AsSelf();
            builder.RegisterComponentInHierarchy<PlayerView>();
            builder.RegisterComponentInHierarchy<ArmsView>();
            builder.RegisterComponentInHierarchy<PlanetView>();
            builder.RegisterComponentInHierarchy<HoldView>();
            builder.Register<HoldWorld>(Lifetime.Singleton);
            // Region sources and spawns are asked in this order: specific ones first, the mines (claim / answer
            // everything) last.
            // The hold's top (gate, great hall; rock round it), and the spawn inside its gate.
            builder.Register<HallSource>(Lifetime.Singleton).As<IRegionSource>().AsSelf();
            builder.Register<IHoldSpawn, HallSpawn>(Lifetime.Singleton);
            builder.Register<IRegionSource, MinesSource>(Lifetime.Singleton);
            builder.Register<IHoldSpawn, MinesSpawn>(Lifetime.Singleton);
            builder.RegisterLuckyNumbersHoldScene();   // generated by Roslyn: HoldPresenter
        }
    }
}
