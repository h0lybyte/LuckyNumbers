using LuckyNumbers.Generated;
using LuckyNumbers.Model;
using VContainer;
using VContainer.Unity;

namespace LuckyNumbers.Planet
{
    /// <summary>Planet (crash site) scene scope; parent is RootLifetimeScope.</summary>
    public sealed class PlanetScope : LifetimeScope
    {
        protected override void Configure(IContainerBuilder builder)
        {
            builder.RegisterInstance(GameContent.Planet);
            builder.RegisterLuckyNumbersPlanet();                                     // generated by Roslyn
            builder.Register<IPromptLine, PlanetPromptLine>(Lifetime.Singleton);       // InteractionPresenter's prompts
            // Two ships here (the wreck and your fighter): PlanetView holds both, so ShipView isn't registered by type.
        }
    }
}
