using LuckyNumbers.Generated;
using LuckyNumbers.Model;
using LuckyNumbers.Planet;
using VContainer;
using VContainer.Unity;

namespace LuckyNumbers.Station
{
    /// <summary>
    /// Outside the station (GameScene.Orbit); parent is RootLifetimeScope. Your universe (Space, shown at once, as
    /// from the station's windows), the crash site's overlay and ships (PlanetView: your fighter, the flight camera)
    /// and the station's hull from outside (OrbitView), flown by OrbitPresenter. Built by SceneBuilder.BuildOrbit.
    /// </summary>
    public sealed class OrbitScope : LifetimeScope
    {
        protected override void Configure(IContainerBuilder builder)
        {
            builder.RegisterInstance(GameContent.Station);
            builder.RegisterInstance(GameContent.Intro.Backdrop);   // your system, as the title left it (instant)
            builder.RegisterLuckyNumbersSpace();                     // generated by Roslyn
            builder.RegisterComponentInHierarchy<PlanetView>();
            builder.RegisterComponentInHierarchy<OrbitView>();
            builder.RegisterEntryPoint<OrbitPresenter>();
        }
    }
}
