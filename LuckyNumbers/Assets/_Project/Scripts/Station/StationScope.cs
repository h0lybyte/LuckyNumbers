using LuckyNumbers.Generated;
using LuckyNumbers.Model;
using LuckyNumbers.Planet;
using VContainer;
using VContainer.Unity;

namespace LuckyNumbers.Station
{
    /// <summary>
    /// Station scene scope; parent is RootLifetimeScope. The player's universe (Space: the same system as the
    /// title, shown at once), first-person control borrowed from the Planet scene (its walk settings, no crash
    /// tremor), the crash site's overlay UI (fade, hint, dialogue: for the call) and the station itself.
    /// </summary>
    public sealed class StationScope : LifetimeScope
    {
        protected override void Configure(IContainerBuilder builder)
        {
            builder.RegisterInstance(GameContent.Station);
            builder.RegisterInstance(GameContent.Intro.Backdrop);   // your system, as the title left it (instant)
            builder.RegisterLuckyNumbersSpace();                     // generated by Roslyn

            var walk = GameContent.Planet.Clone();                   // same feel as on the planet...
            walk.CrashTremorDegrees = 0f;                            // ...but nobody just crashed
            builder.RegisterInstance(walk);
            builder.RegisterEntryPoint<FirstPersonPresenter>().AsSelf();
            builder.RegisterComponentInHierarchy<PlayerView>();
            builder.RegisterComponentInHierarchy<ArmsView>();
            builder.RegisterComponentInHierarchy<PlanetView>();
            builder.RegisterComponentInHierarchy<StationView>();
            builder.RegisterComponentInHierarchy<LuckyNumbers.Core.ShipView>();   // your ship, docked
            builder.RegisterLuckyNumbersStation();                   // generated by Roslyn: StationPresenter
        }
    }
}
