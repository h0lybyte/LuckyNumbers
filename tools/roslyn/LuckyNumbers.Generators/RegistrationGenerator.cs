using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace LuckyNumbers.Generators
{
    /// <summary>
    /// [Presenter] classes -> builder.RegisterEntryPoint&lt;T&gt;()
    /// [View] MonoBehaviours -> builder.RegisterComponentInHierarchy&lt;T&gt;()
    /// emitted as one extension method per assembly: builder.Register&lt;AssemblyName&gt;().
    /// </summary>
    [Generator]
    public sealed class RegistrationGenerator : IIncrementalGenerator
    {
        const string PresenterAttribute = "LuckyNumbers.PresenterAttribute";
        const string ViewAttribute = "LuckyNumbers.ViewAttribute";

        static readonly DiagnosticDescriptor ViewNotMonoBehaviour = new(
            "LN0001", "[View] requires a MonoBehaviour",
            "'{0}' has [View] but doesn't derive from UnityEngine.MonoBehaviour",
            "LuckyNumbers", DiagnosticSeverity.Error, isEnabledByDefault: true);

        static readonly DiagnosticDescriptor PresenterAbstract = new(
            "LN0002", "[Presenter] can't be abstract",
            "'{0}' has [Presenter] but is abstract or static",
            "LuckyNumbers", DiagnosticSeverity.Error, isEnabledByDefault: true);

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var presenters = Collect(context, PresenterAttribute);
            var views = Collect(context, ViewAttribute);
            var assembly = context.CompilationProvider.Select((c, _) => c.AssemblyName ?? "Assembly");

            context.RegisterSourceOutput(presenters.Combine(views).Combine(assembly), (spc, data) =>
            {
                var ((presenterTypes, viewTypes), assemblyName) = data;
                if (presenterTypes.IsEmpty && viewTypes.IsEmpty) return;

                var ok = true;
                foreach (var t in presenterTypes.Where(t => t.IsAbstractOrStatic))
                {
                    spc.ReportDiagnostic(Diagnostic.Create(PresenterAbstract, t.Location, t.Name));
                    ok = false;
                }
                foreach (var t in viewTypes.Where(t => !t.IsMonoBehaviour))
                {
                    spc.ReportDiagnostic(Diagnostic.Create(ViewNotMonoBehaviour, t.Location, t.Name));
                    ok = false;
                }
                if (!ok) return;

                spc.AddSource("Registration.g.cs", Emit(assemblyName, presenterTypes, viewTypes));
            });
        }

        static IncrementalValueProvider<ImmutableArray<TypeInfo>> Collect(
            IncrementalGeneratorInitializationContext context, string attribute) =>
            context.SyntaxProvider.ForAttributeWithMetadataName(
                    attribute,
                    (node, _) => node is ClassDeclarationSyntax,
                    (ctx, _) => TypeInfo.From((INamedTypeSymbol)ctx.TargetSymbol, ctx.TargetNode.GetLocation()))
                .Collect()
                .Select((items, _) => items.OrderBy(t => t.FullName, System.StringComparer.Ordinal).ToImmutableArray());

        static string Emit(string assemblyName, ImmutableArray<TypeInfo> presenters, ImmutableArray<TypeInfo> views)
        {
            var name = new string(assemblyName.Where(char.IsLetterOrDigit).ToArray());
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// Generated by LuckyNumbers.Generators (Roslyn) from [Presenter]/[View] attributes. Do not edit.");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine("namespace LuckyNumbers.Generated");
            sb.AppendLine("{");
            sb.AppendLine($"    public static class {name}Registration");
            sb.AppendLine("    {");
            sb.AppendLine($"        /// <summary>Registers every [Presenter] (entry point) and [View] in {assemblyName}.</summary>");
            sb.AppendLine($"        public static void Register{name}(this global::VContainer.IContainerBuilder builder)");
            sb.AppendLine("        {");
            foreach (var p in presenters)
                sb.AppendLine($"            global::VContainer.Unity.ContainerBuilderUnityExtensions.RegisterEntryPoint<{p.FullName}>(builder, global::VContainer.Lifetime.Singleton);");
            foreach (var v in views)
                sb.AppendLine($"            global::VContainer.Unity.ContainerBuilderUnityExtensions.RegisterComponentInHierarchy<{v.FullName}>(builder);");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        /// <summary>Value-equatable snapshot, so the incremental pipeline can cache.</summary>
        readonly struct TypeInfo : System.IEquatable<TypeInfo>
        {
            public readonly string FullName, Name;
            public readonly bool IsMonoBehaviour, IsAbstractOrStatic;
            public readonly Location Location;

            TypeInfo(string fullName, string name, bool mono, bool abstractOrStatic, Location location)
            {
                FullName = fullName; Name = name; IsMonoBehaviour = mono; IsAbstractOrStatic = abstractOrStatic; Location = location;
            }

            public static TypeInfo From(INamedTypeSymbol symbol, Location location)
            {
                var mono = false;
                for (var b = symbol.BaseType; b != null; b = b.BaseType)
                    if (b.ToDisplayString() == "UnityEngine.MonoBehaviour") { mono = true; break; }
                return new TypeInfo(symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), symbol.Name,
                    mono, symbol.IsAbstract || symbol.IsStatic, location);
            }

            public bool Equals(TypeInfo o) => FullName == o.FullName && IsMonoBehaviour == o.IsMonoBehaviour
                                              && IsAbstractOrStatic == o.IsAbstractOrStatic;
            public override bool Equals(object? obj) => obj is TypeInfo o && Equals(o);
            public override int GetHashCode() => FullName.GetHashCode();
        }
    }
}
