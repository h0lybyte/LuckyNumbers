using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace LuckyNumbers.Generators
{
    /// <summary>
    /// [Ui("name")] fields -> a generated BindUi(VisualElement root) on the containing partial class that
    /// assigns each field from root.Q&lt;T&gt;("name") and throws if the UXML lacks the element.
    /// </summary>
    [Generator]
    public sealed class UiBindingGenerator : IIncrementalGenerator
    {
        const string UiAttribute = "LuckyNumbers.UiAttribute";

        static readonly DiagnosticDescriptor NotPartial = new(
            "LN0003", "[Ui] fields need a partial class",
            "'{0}' has [Ui] fields but isn't declared partial",
            "LuckyNumbers", DiagnosticSeverity.Error, isEnabledByDefault: true);

        static readonly DiagnosticDescriptor Nested = new(
            "LN0004", "[Ui] fields can't be in nested classes",
            "'{0}' is nested; declare it at namespace level",
            "LuckyNumbers", DiagnosticSeverity.Error, isEnabledByDefault: true);

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var fields = context.SyntaxProvider.ForAttributeWithMetadataName(
                    UiAttribute,
                    (node, _) => node is VariableDeclaratorSyntax,
                    (ctx, _) => Field.From((IFieldSymbol)ctx.TargetSymbol, ctx.Attributes[0], ctx.TargetNode.GetLocation()))
                .Collect();

            context.RegisterSourceOutput(fields, (spc, all) =>
            {
                foreach (var group in all.GroupBy(f => f.TypeFullName).OrderBy(g => g.Key, System.StringComparer.Ordinal))
                {
                    var first = group.First();
                    if (!first.TypeIsPartial) { spc.ReportDiagnostic(Diagnostic.Create(NotPartial, first.Location, first.TypeName)); continue; }
                    if (first.TypeIsNested) { spc.ReportDiagnostic(Diagnostic.Create(Nested, first.Location, first.TypeName)); continue; }
                    spc.AddSource($"{first.TypeName}.UiBinding.g.cs", Emit(first, group.OrderBy(f => f.FieldName, System.StringComparer.Ordinal)));
                }
            });
        }

        static string Emit(Field type, System.Collections.Generic.IEnumerable<Field> fields)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// Generated by LuckyNumbers.Generators (Roslyn) from [Ui] fields. Do not edit.");
            sb.AppendLine("// </auto-generated>");
            var ns = type.Namespace;
            if (ns.Length > 0) sb.AppendLine($"namespace {ns}").AppendLine("{");
            sb.AppendLine($"    partial class {type.TypeName}");
            sb.AppendLine("    {");
            sb.AppendLine("        /// <summary>Assigns every [Ui] field from the UXML tree under <paramref name=\"root\"/>.</summary>");
            sb.AppendLine("        void BindUi(global::UnityEngine.UIElements.VisualElement root)");
            sb.AppendLine("        {");
            foreach (var f in fields)
            {
                var name = SymbolDisplay.FormatLiteral(f.ElementName, quote: true);
                sb.AppendLine($"            {f.FieldName} = global::UnityEngine.UIElements.UQueryExtensions.Q<{f.FieldType}>(root, {name})");
                sb.AppendLine($"                ?? throw new global::System.InvalidOperationException(\"{type.TypeName}: no <{f.FieldTypeShort}> named \" + {name} + \" in the UXML\");");
            }
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            if (ns.Length > 0) sb.AppendLine("}");
            return sb.ToString();
        }

        readonly struct Field : System.IEquatable<Field>
        {
            public readonly string TypeFullName, TypeName, Namespace, FieldName, FieldType, FieldTypeShort, ElementName;
            public readonly bool TypeIsPartial, TypeIsNested;
            public readonly Location Location;

            Field(string typeFullName, string typeName, string ns, string fieldName, string fieldType, string fieldTypeShort,
                  string elementName, bool partial, bool nested, Location location)
            {
                TypeFullName = typeFullName; TypeName = typeName; Namespace = ns; FieldName = fieldName;
                FieldType = fieldType; FieldTypeShort = fieldTypeShort; ElementName = elementName;
                TypeIsPartial = partial; TypeIsNested = nested; Location = location;
            }

            public static Field From(IFieldSymbol field, AttributeData attribute, Location location)
            {
                var type = field.ContainingType;
                var partial = type.DeclaringSyntaxReferences.Any(r =>
                    r.GetSyntax() is ClassDeclarationSyntax c && c.Modifiers.Any(m => m.IsKind(SyntaxKind.PartialKeyword)));
                var element = attribute.ConstructorArguments.Length > 0 ? attribute.ConstructorArguments[0].Value as string ?? "" : "";
                return new Field(type.ToDisplayString(), type.Name,
                    type.ContainingNamespace.IsGlobalNamespace ? "" : type.ContainingNamespace.ToDisplayString(),
                    field.Name, field.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), field.Type.Name,
                    element, partial, type.ContainingType != null, location);
            }

            public bool Equals(Field o) => TypeFullName == o.TypeFullName && FieldName == o.FieldName && FieldType == o.FieldType
                                           && ElementName == o.ElementName && TypeIsPartial == o.TypeIsPartial;
            public override bool Equals(object? obj) => obj is Field o && Equals(o);
            public override int GetHashCode() => (TypeFullName + "." + FieldName).GetHashCode();
        }
    }
}
